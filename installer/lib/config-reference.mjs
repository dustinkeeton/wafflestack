// @ts-check
// `.waffle/waffle.reference.yaml` (#703): every config key a selection can set, as commented-out
// YAML. Built from stack declarations only — never from config values — so no `waffle.yaml` or
// `waffle.local.yaml` value can reach a committed file (#317).

import path from 'node:path';
import { isDeepStrictEqual } from 'node:util';
import YAML from 'yaml';
import { configCatalog, mergeCatalog, specFacts, summaryOf } from './config-catalog.mjs';

/** @import { MergedKey } from './config-catalog.mjs' */
/** @import { SelectionItem } from './refs.mjs' */
/** @import { Target } from './project.mjs' */

export const CONFIG_REFERENCE = path.join('.waffle', 'waffle.reference.yaml');

const VALUE_MAX = 110;

/**
 * @typedef {object} TreeNode
 * @property {Map<string, TreeNode>} children
 * @property {MergedKey} [leaf]
 */

/** @param {MergedKey} k */
const stacksOf = (k) => [...new Set(k.decls.map((d) => d.stackName))].sort();

/** @param {MergedKey} k */
const isMustSet = (k) => k.decls.some((d) => !!d.spec?.required && d.spec?.default === undefined);

/** @param {MergedKey} k */
const isLocked = (k) => !k.conflict && k.decls[0].spec?.lockMode !== undefined;

/**
 * The YAML lines for `leaf: default`, or the reason it is a comment instead.
 * @param {string} leaf
 * @param {MergedKey} k
 * @param {boolean} collides the key is also a dotted prefix of other keys
 * @returns {{ lines: string[] } | { reason: string }}
 */
function leafValue(leaf, k, collides) {
  if (k.conflict) return { reason: 'declarations disagree' };
  if (collides) return { reason: 'also a prefix of other keys' };
  const spec = k.decls[0].spec ?? {};
  const def = spec.default;
  if (def === undefined || def === null) return { reason: 'optional, no default' };
  if (typeof def === 'string' && def.includes('\n')) return { reason: `multi-line default, ${def.split('\n').length} lines` };
  const json = JSON.stringify(def);
  if (json.length > VALUE_MAX) return { reason: `default is ${json.length} chars` };
  if (Array.isArray(spec.configModes) && !spec.configModes.some((/** @type {any} */ m) => isDeepStrictEqual(m, def))) {
    return { reason: 'default is outside configModes' };
  }
  const text = YAML.stringify({ [leaf]: def }, { lineWidth: 0 }).trimEnd();
  if (!isDeepStrictEqual(YAML.parse(text)?.[leaf], def)) return { reason: 'default does not round-trip as YAML' };
  return { lines: text.split('\n') };
}

/** @param {TreeNode} node */
function hasValue(node) {
  if (node.leaf && !node.children.size && !('reason' in leafValue('x', node.leaf, false))) return true;
  return [...node.children.values()].some(hasValue);
}

/**
 * @param {TreeNode} node
 * @param {number} depth
 * @param {string[]} out
 */
function emitTree(node, depth, out) {
  const pad = '  '.repeat(depth);
  const names = [...node.children.keys()].sort((a, b) => a.localeCompare(b));
  for (const name of names) {
    const child = /** @type {TreeNode} */ (node.children.get(name));
    if (child.leaf) {
      const k = child.leaf;
      const spec = k.decls[0].spec;
      const summary = summaryOf(spec?.description);
      if (summary) out.push(`# ${pad}# ${summary}`);
      const meta = [`${stacksOf(k).length > 1 ? 'stacks' : 'stack'}: ${stacksOf(k).join(', ')}`];
      for (const [label, v] of specFacts(spec)) meta.push(`${label}: ${v}`);
      out.push(`# ${pad}# ${meta.join(' · ')}`);
      const v = leafValue(name, k, child.children.size > 0);
      if ('lines' in v) out.push(...v.lines.map((l) => `# ${pad}${l}`));
      else out.push(`# ${pad}# ${name}: (${v.reason} — wafflestack config ${k.key})`);
    }
    if (!child.children.size) continue;
    out.push(hasValue(child) ? `# ${pad}${name}:` : `# ${pad}# ${name}:`);
    emitTree(child, depth + 1, out);
  }
}

/**
 * The reference file's text for a merged catalog. Reads declarations only (`key`, `required`,
 * `conflict`, `decls[].stackName/spec`) — never a resolved value.
 *
 * @param {MergedKey[]} merged
 * @returns {string|null} null when no key is in scope
 */
export function configReferenceYaml(merged) {
  if (!merged.length) return null;
  const mustSet = merged.filter(isMustSet);
  const locked = merged.filter((k) => !isMustSet(k) && isLocked(k));
  const rest = merged.filter((k) => !isMustSet(k) && !isLocked(k));

  const out = [
    '## .waffle/waffle.reference.yaml — every config key this selection can set.',
    '## Generated by `wafflestack render` from stack declarations only, never from waffle.yaml or',
    '## waffle.local.yaml values. Do not edit: re-render instead.',
    '##',
    '## Lines starting `## ` are notes; lines starting `# ` are YAML. Copy the `# config:` line and',
    '## any block below it into .waffle/waffle.yaml (merge under an existing `config:` if there is',
    '## one), then strip one leading `# ` from each line.',
    '## Full detail on a key: wafflestack config <key>',
    '## `harness.*` keys are built-ins, not config — see schema/FORMAT.md, "The `harness.*` namespace".',
  ];
  if (mustSet.length) {
    out.push('##', '## Must set — required with no default; set each in the committed .waffle/waffle.yaml:');
    for (const k of mustSet) {
      const summary = summaryOf(k.decls[0].spec?.description);
      const warn = k.conflict ? ' ⚠ declarations disagree' : '';
      out.push(`##   ${k.key}${summary ? ` — ${summary}` : ''} [${stacksOf(k).join(', ')}]${warn}`);
    }
  }
  if (locked.length) {
    out.push('##', '## Locked — config cannot change these; only the skill\'s per-run flag token can:');
    for (const k of locked) {
      const spec = k.decls[0].spec;
      const flag = specFacts(spec).find(([label]) => label === 'flag');
      out.push(`##   ${k.key} = ${JSON.stringify(spec.lockMode)}${flag ? ` (flag: ${flag[1]})` : ''} [${stacksOf(k).join(', ')}]`);
    }
  }
  if (rest.length) {
    /** @type {TreeNode} */
    const root = { children: new Map() };
    for (const k of rest) {
      let node = root;
      for (const seg of k.key.split('.')) {
        if (!node.children.has(seg)) node.children.set(seg, { children: new Map() });
        node = /** @type {TreeNode} */ (node.children.get(seg));
      }
      node.leaf = k;
    }
    out.push('', hasValue(root) ? '# config:' : '# # config:');
    emitTree(root, 1, out);
  }
  return `${out.join('\n')}\n`;
}

/**
 * The reference file for a render selection. `values: {}` is the structural no-leak guarantee:
 * the catalog never sees a project value.
 *
 * @param {{ selection: { items: SelectionItem[] }, target: Target }} opts
 * @returns {string|null}
 */
export function generateConfigReference({ selection, target }) {
  return configReferenceYaml(mergeCatalog(configCatalog(selection.items, { values: {}, target })));
}
